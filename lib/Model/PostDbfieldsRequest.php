                sprintf(
                    "Invalid value '%s' for 'field_type_intern_code', must be one of '%s'",
                    $field_type_intern_code,
                    implode("', '", $allowedValues)
                )
            );
        }
        $this->container['field_type_intern_code'] = $field_type_intern_code;

        return $this;
    }
